//! The manifest's JSON Schema (draft 2020-12), generated from [`crate::manifest`]'s types and committed as
//! `integrations/connectors/connector.schema.json` (editors validate and complete `connector.yaml` with it).

use serde_json::{json, Value};
use utoipa::OpenApi;

#[derive(OpenApi)]
#[openapi(components(schemas(crate::manifest::Manifest)))]
struct Doc;

/// The schema document.
pub fn json_schema() -> Value {
    let doc = serde_json::to_value(Doc::openapi()).expect("schema");
    let defs = doc.pointer("/components/schemas").cloned().unwrap_or_else(|| json!({}));
    let text = defs.to_string().replace("#/components/schemas/", "#/$defs/");
    let mut defs: Value = serde_json::from_str(&text).expect("schema");
    let snapshot = defs.clone();
    strict_variants(&mut defs, &snapshot);
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://observecraft.dev/schemas/connector.schema.json",
        "title": "ObserveCraft connector package (connector.yaml)",
        "description": "Generated by `oc-connector schema` from server/crates/oc-connectors/src/manifest.rs; see docs/connectors.md.",
        "$ref": "#/$defs/Manifest",
        "$defs": defs,
    })
}

/// Tagged enums (`kind: …`) as utoipa writes them don't refuse unknown fields, and their variants holding a struct
/// are `allOf` of the struct (which refuses `kind`) and the tag: each variant becomes one closed object.
fn strict_variants(v: &mut Value, defs: &Value) {
    match v {
        Value::Object(o) => {
            if let Some(Value::Array(variants)) = o.get_mut("oneOf") {
                for variant in variants.iter_mut() {
                    let tagged = variant.pointer("/properties/kind").is_some();
                    if let Some(Value::Array(parts)) = variant.get("allOf").cloned() {
                        let target = parts.iter().find_map(|p| p.get("$ref").and_then(Value::as_str)).and_then(|r| r.strip_prefix("#/$defs/")).and_then(|name| defs.get(name));
                        let tag = parts.iter().find(|p| p.pointer("/properties/kind").is_some());
                        if let (Some(target), Some(tag)) = (target, tag) {
                            let mut merged = target.clone();
                            merged["properties"]["kind"] = tag["properties"]["kind"].clone();
                            let mut required = merged["required"].as_array().cloned().unwrap_or_default();
                            required.push(json!("kind"));
                            merged["required"] = Value::Array(required);
                            merged["additionalProperties"] = json!(false);
                            if let Some(d) = variant.get("description").cloned() {
                                merged["description"] = d;
                            }
                            *variant = merged;
                        }
                    } else if tagged {
                        variant["additionalProperties"] = json!(false);
                    }
                }
            }
            for child in o.values_mut() {
                strict_variants(child, defs);
            }
        }
        Value::Array(a) => a.iter_mut().for_each(|c| strict_variants(c, defs)),
        _ => {}
    }
}

/// The committed file's text.
pub fn json_schema_text() -> String {
    serde_json::to_string_pretty(&json_schema()).expect("schema") + "\n"
}

#[cfg(test)]
mod tests {
    /// The committed schema is the generated one (`oc-connector schema > integrations/connectors/connector.schema.json`).
    #[test]
    fn the_committed_schema_is_current() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../integrations/connectors/connector.schema.json");
        let text = super::json_schema_text();
        if std::env::var("OC_CONNECTOR_UPDATE").is_ok_and(|v| v == "1") {
            std::fs::write(path, &text).unwrap();
        }
        let committed = std::fs::read_to_string(path).unwrap_or_default();
        assert!(committed == text, "integrations/connectors/connector.schema.json is out of date: OC_CONNECTOR_UPDATE=1 cargo test -p oc-connectors schema");
        let doc: serde_json::Value = serde_json::from_str(&text).unwrap();
        let auth = &doc["$defs"]["Auth"]["oneOf"];
        assert!(auth.as_array().unwrap().iter().all(|v| v["additionalProperties"] == false && v["properties"]["kind"].is_object()), "{auth}");
    }
}

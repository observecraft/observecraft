// Writes the logo of every integrations-core catalog integration that has one in SVG Logos or
// Simple Icons (both CC0) to src/assets/integrationLogos.generated.ts, keyed by integration id.
// The Integrations page loads it on demand (it is a few hundred KB).
// Run: npm run logos:integrations   (after scripts/import-integration-catalog.mjs, or after editing the aliases)
import { readFileSync, writeFileSync } from 'node:fs';
import { loadLibraries, matchIntegrationLogo } from './integrationLogoMatch.mjs';

const catalog = JSON.parse(readFileSync(new URL('../src/api/integrations/catalog.generated.json', import.meta.url), 'utf8')).integrations;
const libraries = loadLibraries();
const set = libraries.logos;

function resolve(name, depth = 0) {
  const icon = set.icons[name];
  if (icon) return icon;
  const alias = set.aliases?.[name];
  if (alias && depth < 3) return { ...resolve(alias.parent, depth + 1), ...alias, parent: undefined };
  return null;
}

const out = {};
for (const integration of catalog) {
  const found = matchIntegrationLogo(integration, libraries);
  if (!found) continue;
  if (found.source === 'logos') {
    const icon = resolve(found.name);
    out[integration.id] = { body: icon.body, width: icon.width ?? set.width ?? 256, height: icon.height ?? set.height ?? 256 };
  } else {
    const icon = libraries.simpleBySlug.get(found.name);
    out[integration.id] = { body: `<path fill="#${icon.hex}" d="${icon.path}"/>`, width: 24, height: 24 };
  }
}

const header = `// GENERATED by scripts/build-integration-logos.mjs from @iconify-json/logos (SVG Logos, CC0-1.0) and
// simple-icons (CC0-1.0), matched to the integrations-core catalog. Do not edit.
// Brand names and logos are trademarks of their owners; shown only to identify the integration.
`;
const file = new URL('../src/assets/integrationLogos.generated.ts', import.meta.url);
writeFileSync(file, `${header}export const INTEGRATION_LOGOS: Record<string, { body: string; width: number; height: number }> = ${JSON.stringify(out, null, 1)};\n`);
console.log(`Wrote ${Object.keys(out).length} of ${catalog.length} integration logos (${Math.round(readFileSync(file).length / 1024)} KB).`);

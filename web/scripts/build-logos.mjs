function resolve(name, depth = 0) {
  const icon = set.icons[name];
  if (icon) return icon;
  const alias = set.aliases?.[name];
  if (alias && depth < 3) return { ...resolve(alias.parent, depth + 1), ...alias, parent: undefined };
  return null;
}

const out = {};
const missing = [];
for (const [key, name] of Object.entries(MAP)) {
  const icon = resolve(name);
  if (!icon) {
    missing.push(`${key} → ${name}`);
    continue;
  }
  out[key] = { body: icon.body, width: icon.width ?? set.width ?? 256, height: icon.height ?? set.height ?? 256 };
}
if (missing.length) {
  console.error(`Missing logos:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}


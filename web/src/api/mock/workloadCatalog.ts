/** The category the agent rules report, from the expression's first event type. */
export function wpCategory(expression: string): string {
  const first = expression.replace(/^[(\s]+/, '').split(/[.\s]/)[0];
  if (['exec', 'fork', 'exit', 'process', 'signal', 'ptrace', 'setuid', 'setgid', 'capset'].includes(first)) return 'Process Activity';
  if (['open', 'chmod', 'chown', 'unlink', 'rename', 'mkdir', 'rmdir', 'link', 'utimes', 'setxattr', 'removexattr', 'mount', 'umount', 'splice'].includes(first)) return 'File Activity';
  if (['dns', 'bind', 'connect', 'accept', 'imds', 'network', 'packet'].includes(first)) return 'Network Activity';
  return 'Kernel Activity';
}

/** Datadog's id form (`abc-d3f-9hi`), stable for a seed. */
export function wpStableId(seed: string): string {
  let h = 0xcbf29ce484222325n;
  for (const b of new TextEncoder().encode(seed)) h = ((h ^ BigInt(b)) * 0x100000001b3n) & 0xffffffffffffffffn;
  const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
  let s = '';
  for (let i = 0; i < 9; i++) {
    if (i > 0 && i % 3 === 0) s += '-';
    s += chars[Number(h % 36n)];
    h /= 36n;
  }
  return s;
}

export const wpPolicyId = (key: string) => wpStableId(`policy:${key}`);
export const wpDetectionRuleId = (agentRule: string) => `def-wp-${agentRule.replace(/_/g, '-')}`;
export function wpMitreTags(r: WpCatalogRule): string[] {
  if (!r.tactic) return [];
  const name = WP_TACTICS.find((t) => t[0] === r.tactic)?.[1] ?? '';
  return [`tactic:${r.tactic}-${name.toLowerCase().replace(/ /g, '-')}`, `technique:${r.technique}`];
}
